from __future__ import annotations

import os
import shutil
import subprocess
import sys
import re
from pathlib import Path
from typing import List

try:
    import kconfiglib
except Exception:
    print("kconfiglib is required. Install with: python -m pip install kconfiglib", file=sys.stderr)
    sys.exit(1)


def find_kconfigs(root: Path, exclude_root: bool = True, exclude_dirs: List[str] | None = None) -> List[Path]:
    exclude_dirs = set(exclude_dirs or [])
    root = root.resolve()
    found: List[Path] = []
    for dirpath, dirnames, filenames in os.walk(root):
        # filter out excluded directories in-place to avoid walking them
        dirnames[:] = [d for d in dirnames if d not in exclude_dirs]
        if "Kconfig" in filenames:
            p = Path(dirpath) / "Kconfig"
            # optionally exclude root/Kconfig
            if exclude_root and p.resolve() == (root / "Kconfig").resolve():
                continue
            found.append(p.resolve())
    found.sort()
    return found


def make_generated_kconfig(root: Path, kconfigs: List[Path], out_file: Path) -> Path:
    """Write an aggregated Kconfig file to the given out_file path and return it.

    out_file: full path to the generated Kconfig file (not a directory).
    """
    out_file = out_file.resolve()
    out_file.parent.mkdir(parents=True, exist_ok=True)

    lines = ["# Auto-generated Kconfig which rsource's discovered Kconfig files\n"]
    for k in kconfigs:
        # relative path from root, use forward slashes and prefix ./
        # Make the rsource path relative to the directory containing the
        # generated Kconfig (out_file.parent). This yields entries like
        # ./rts/Kconfig when the aggregate Kconfig is written at the project
        # root and the discovered Kconfig lives in ./rts/Kconfig.
        rel = os.path.relpath(str(k), start=str(out_file.parent)).replace("\\", "/")
        lines.append(f'rsource "./{rel}"\n')

    out_file.write_text("".join(lines), encoding="utf-8")
    return out_file


def main(search_root: Path | str, out_file: Path | str) -> int:
    """Main entrypoint.

    Args:
      search_root: directory to search for Kconfig files (root of project)
      out_file: path to write the generated aggregated Kconfig file

    Returns: exit code (0 success, non-zero error codes kept compatible with previous behavior)
    """
    root = Path(search_root).resolve()
    # out_file参数改为头文件路径名，聚合Kconfig.projbuild与menuconfig入口都基于此路径
    out_file = Path(out_file).resolve()
    out_dir = out_file.parent
    kconfig_projbuild = out_dir / "Kconfig.projbuild"

    print(f"Scanning for Kconfig files under: {root}")
    # include the Kconfig in the search_root itself (useful when scanning a
    # subdirectory like 'rts'). Exclude common build directories.
    kconfigs = find_kconfigs(root, exclude_root=False, exclude_dirs=[".git", "build", "out"])

    if not kconfigs:
        print("No Kconfig files found.")
        return 2

    print(f"Found {len(kconfigs)} Kconfig files:")
    for k in kconfigs:
        print("  -", k)

    generated = make_generated_kconfig(root, kconfigs, kconfig_projbuild)
    print(f"Generated aggregated Kconfig at: {generated}")

    # Use kconfiglib's built-in UI to configure interactively.
    # Create a Kconfig instance pointing at the generated aggregate Kconfig.
    try:
        kconf = kconfiglib.Kconfig(str(kconfig_projbuild))
    except Exception as e:
        print(f"Failed to parse generated Kconfig with kconfiglib: {e}", file=sys.stderr)
        return 3

    # decide config path (we'll read existing and write back to this path)
    config_path = out_dir / ".config"
    # Do not pre-load .config here; the external frontend will read/write it.
    # We will load it after the external frontend exits to generate the header.

    # Always run an external menuconfig-like frontend named 'menuconfig'，并指定Kconfig.projbuild为入口
    cmd_list = ["menuconfig", str(kconfig_projbuild)]
    try:
        env = os.environ.copy()
        # set srctree so rsource paths resolve
        env["srctree"] = str(root).replace('\\', '/')
        rc = subprocess.call(cmd_list, cwd=str(out_dir), env=env)
        if rc != 0:
            print(f"External menuconfig exited with code {rc}", file=sys.stderr)
            return rc
    except FileNotFoundError:
        print(f"External command not found: {cmd_list[0]}", file=sys.stderr)
        return 127

    # After the interactive session, load the .config generated by the external
    # frontend and write the autoconf-style header. Do NOT overwrite the
    # user's .config with the (stale) kconf instance.
    try:
        header_path = out_dir / "rts_cfg.h"
        if config_path.exists():
            kconf.load_config(str(config_path))
            kconf.write_autoconf(str(header_path))
            print(f"Loaded .config from {config_path}")
            print(f"Generated header with kconfiglib: {header_path}")
        else:
            print(f"No .config produced by external frontend at {config_path}; skipping header generation", file=sys.stderr)
    except Exception as e:
        print(f"Failed to generate header from .config: {e}", file=sys.stderr)

    # Add include guard to generated header if missing
    try:
        if header_path.exists():
            text = header_path.read_text(encoding="utf-8")
            if not re.search(r"#ifndef\s+[A-Z0-9_]+", text):
                # make a guard based on filename
                base = header_path.stem.upper()
                guard = re.sub(r"[^A-Z0-9]", "_", base) + "_H_"
                guard = "_" + guard
                new = []
                new.append(f"/* Auto-generated - do not edit. */\n")
                new.append(f"#ifndef {guard}\n#define {guard}\n\n")
                new.append(text)
                if not text.endswith("\n"):
                    new.append("\n")
                new.append(f"\n#endif /* {guard} */\n")
                header_path.write_text(''.join(new), encoding="utf-8")
                print(f"Added include guard {guard} to {header_path}")
    except Exception as e:
        print(f"Failed to postprocess header guard: {e}", file=sys.stderr)

    # Interactive session completed successfully if we reached here
    print("menuconfig (kconfiglib UI) completed.")

    return 0


if __name__ == "__main__":
    # Fallback: search当前目录，头文件路径为rts_cfg.h
    sys.exit(main(Path.cwd(), Path.cwd() /"rts_cfg.h"))